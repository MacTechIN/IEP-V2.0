-- 012: 녹취 한 줄이 어느 녹음에서 왔는지
--
-- 왜 필요한가
--   전사가 틀린 것 같아도 **원본을 들어볼 방법이 없다.** 어제 녹취 편집을 넣었는데,
--   고칠지 말지 판단할 근거가 화면에 없다 — 전사 일치도가 64~70% 라
--   고유명사와 숫자는 자주 틀린다.
--
--   그런데 줄을 눌러 그 대목을 들으려면 **어느 파일의 몇 초인지**를 알아야 한다.
--   지금은 둘 다 없다.
--
-- 왜 시각만으로는 안 되나
--   미팅 하나에 녹음이 여러 개일 수 있고(파트 1~4), 각 녹음의 전사는
--   **그 파일의 0초부터** 시작한다. 분석 워크플로가 그것을 보정 없이 이어붙이므로
--   시각이 파일 수만큼 0으로 돌아간다.
--
--   실측(미팅 876b8403, 녹음 4개·세그먼트 404개):
--     #97 625초 → 0초 · #184 609초 → 0초 · #313 580초 → 1초
--
--   즉 `start_ms` 는 **어느 파일 기준인지 함께 알아야** 뜻이 선다.
--
-- 왜 on delete set null 인가
--   녹음을 지워도 전사는 남아야 한다. 전사문이 분석의 근거이고,
--   오디오가 없다고 그것까지 지울 이유가 없다.
-- ===================================================================

alter table v2.transcript_segments
  add column if not exists recording_id uuid
    references v2.meeting_recordings(id) on delete set null;

comment on column v2.transcript_segments.recording_id is
  '이 줄이 나온 녹음. start_ms 는 이 파일의 0초 기준이다 — 둘을 함께 봐야 재생 위치가 된다.';

-- 재생기가 "이 녹음의 줄들" 을 찾을 때 쓴다. 대부분의 옛 행은 null 이므로 부분 인덱스로 둔다.
create index if not exists idx_transcript_segments_recording
  on v2.transcript_segments (recording_id, sort_order)
  where recording_id is not null;

-- ── 기존 행은 보정하지 않는다
--
-- 어느 녹음에서 왔는지 알 방법이 없다. `sort_order` 로 추측할 수는 있지만
-- **틀리면 엉뚱한 오디오를 튼다** — 사용자는 그것을 믿고 "전사가 맞다/틀리다" 를 판단한다.
-- 잘못된 위치는 없는 것보다 나쁘다.
--
-- 화면은 `recording_id` 가 없으면 재생 이동 버튼을 감춘다. 다시 분석하면 채워진다.
