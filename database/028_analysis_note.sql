-- 028: 분석이 「무엇을 못 했는지」 말하게 한다
--
-- ── 무엇이 문제였나 ──────────────────────────────────────────
--
-- 2026-08-26 베타 전 점검에서 실측했다. 녹음이 붙지 않은 상담을 분석하면 —
--
--   전사 0자  →  analysis_status = 'completed', 진행률 100%
--             →  findings 0 · 시계열 0 · 증거 0 · 요건 갱신 0
--
-- SEP 에서는 제목·메모만으로 요약하는 **정상 모드**였다. 법률 상담에서는 다르다:
-- 사실관계 탭이 텅 빈 채 「완료」라고 뜨면 변호사는 **상담에서 건질 것이 없었다고 읽는다.**
-- 실제로는 분석이 아예 돌지 않은 것이다.
--
-- **실패가 아니라서 `analysis_error` 에 담을 수 없다.** 실패로 표시하면 이번에는
-- 정상인 메타데이터 요약까지 빨갛게 뜬다. 실패도 성공도 아닌 **「덜 된 것」**을 담을 칸이 없었다.
--
-- ── 이 저장소는 이미 이 원칙을 안다 ──────────────────────────
--
-- `meeting_recordings.transcribe_notes`(014)가 같은 자리다 — 전사가 조용히 저하됐을 때
-- 그것을 화면에 말해 주려고 만들었다. 분석에는 그 칸이 없었다.
--
-- **되돌리기**
--   alter table v2.meetings drop column analysis_note;

alter table v2.meetings
  add column if not exists analysis_note text;

comment on column v2.meetings.analysis_note is
  '분석이 무엇을 못 했는지 (028). 실패는 아니지만 덜 된 것. **비어 있으면 온전히 끝난 것이다** — 화면은 이 값이 있을 때만 안내를 띄운다.';
